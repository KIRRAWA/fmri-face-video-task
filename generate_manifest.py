#!/usr/bin/env python3
"""Scan the videos/ directory and generate videos/manifest.js (the video manifest).

Usage:
    python3 generate_manifest.py

A page opened via file:// cannot list a directory, so the manifest declares the
video files. Rerun this script whenever videos are added to or removed from videos/.
Supported formats: .mp4 .webm .m4v (playable by Chrome; H.264 + AAC MP4 recommended).

Each entry carries {src, author, nick, desc} read from videos/authors.json
(written by download_videos.py / get_authors.py); missing metadata becomes "".
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
VDIR = os.path.join(HERE, "videos")
EXTS = (".mp4", ".webm", ".m4v")

os.makedirs(VDIR, exist_ok=True)

authors = {}
try:
    with open(os.path.join(VDIR, "authors.json"), encoding="utf-8") as fp:
        authors = json.load(fp)
except (OSError, json.JSONDecodeError):
    pass  # no metadata yet — entries get empty strings

files = sorted(
    f for f in os.listdir(VDIR)
    if f.lower().endswith(EXTS) and not f.startswith(".")
)
entries = []
for f in files:
    vid = os.path.splitext(f)[0]
    meta = authors.get(vid, {})
    entries.append({
        "src": "videos/" + f,
        "author": meta.get("author", ""),
        "nick": meta.get("nick", ""),
        "desc": meta.get("desc", ""),
    })

header = (
    "// Video manifest (auto-generated by generate_manifest.py — do not edit by hand;\n"
    "// rerun the script after adding/removing videos).\n"
    "// Paths are relative to index.html. Empty array = built-in placeholder clips.\n"
    "// Each entry: { src, author, nick, desc } — author/nick/desc come from videos/authors.json.\n"
)
js = header + "window.VIDEO_MANIFEST = " + json.dumps(entries, ensure_ascii=False, indent=1) + ";\n"

with open(os.path.join(VDIR, "manifest.js"), "w", encoding="utf-8") as fp:
    fp.write(js)

print(f"Wrote {len(entries)} video(s) to videos/manifest.js")
for e in entries:
    print(f"  {e['src']}  @{e['author'] or 'unknown'}")
